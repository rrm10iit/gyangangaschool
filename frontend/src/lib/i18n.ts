const dicts: Record<Lang, Dict> = { en, hi };

export function tr(lang: Lang, key: string, vars?: Record<string, string>): string {
  let s = dicts[lang][key] ?? dicts.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
}

/** Picks the Hindi text when the language is Hindi and a translation exists, else the English text. */
export function pick(lang: Lang, en?: string | null, hi?: string | null): string {
  if (lang === 'hi' && hi && hi.trim()) return hi;
  return en ?? '';
}
