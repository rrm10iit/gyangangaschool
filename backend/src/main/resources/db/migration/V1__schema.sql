-- Gyan Ganga School: initial schema

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(190) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    full_name     VARCHAR(150) NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_app_user_email ON app_user (lower(email));

CREATE TABLE school_class (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(60)  NOT NULL UNIQUE,
    display_order INT          NOT NULL DEFAULT 0,
    description   TEXT,
    description_hi TEXT,
    subjects      VARCHAR(500),
    sections      VARCHAR(100) NOT NULL DEFAULT 'A',
    seats         INT,
    age_group     VARCHAR(60),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE student (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admission_no   VARCHAR(40)  NOT NULL UNIQUE,
    full_name      VARCHAR(150) NOT NULL,
    class_id       BIGINT       NOT NULL REFERENCES school_class (id),
    section        VARCHAR(10),
    roll_no        INT,
    date_of_birth  DATE,
    gender         VARCHAR(10),
    guardian_name  VARCHAR(150),
    guardian_phone VARCHAR(30),
    guardian_email VARCHAR(190),
    contact_phone  VARCHAR(30),
    address        VARCHAR(500),
    photo_url      VARCHAR(300),
    admission_date DATE,
    fee_discount   NUMERIC(12, 2) NOT NULL DEFAULT 0,
    status         VARCHAR(15)  NOT NULL DEFAULT 'ACTIVE',
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_student_class ON student (class_id);
CREATE INDEX ix_student_name ON student (lower(full_name));

CREATE TABLE student_document (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT       NOT NULL REFERENCES student (id) ON DELETE CASCADE,
    name       VARCHAR(150) NOT NULL,
    file_url   VARCHAR(300) NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_student_document_student ON student_document (student_id);

CREATE TABLE teacher (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_no      VARCHAR(40)  NOT NULL UNIQUE,
    full_name        VARCHAR(150) NOT NULL,
    subjects         VARCHAR(300),
    classes_assigned VARCHAR(300),
    qualification    VARCHAR(200),
    phone            VARCHAR(30),
    email            VARCHAR(190),
    address          VARCHAR(500),
    joining_date     DATE,
    photo_url        VARCHAR(300),
    monthly_salary   NUMERIC(12, 2) NOT NULL DEFAULT 0,
    active           BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE fee_structure (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id   BIGINT         NOT NULL REFERENCES school_class (id),
    head_name  VARCHAR(100)   NOT NULL,
    amount     NUMERIC(12, 2) NOT NULL,
    frequency  VARCHAR(15)    NOT NULL,
    created_at TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ    NOT NULL DEFAULT now()
);
CREATE INDEX ix_fee_structure_class ON fee_structure (class_id);

CREATE SEQUENCE receipt_seq START 1;

CREATE TABLE fee_payment (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_no    VARCHAR(40)    NOT NULL UNIQUE,
    student_id    BIGINT         NOT NULL REFERENCES student (id),
    amount        NUMERIC(12, 2) NOT NULL,
    payment_date  DATE           NOT NULL,
    academic_year INT            NOT NULL,
    mode          VARCHAR(15)    NOT NULL,
    for_period    VARCHAR(100),
    reference     VARCHAR(100),
    remarks       VARCHAR(300),
    collected_by  VARCHAR(190),
    created_at    TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ    NOT NULL DEFAULT now()
);
CREATE INDEX ix_fee_payment_student ON fee_payment (student_id, academic_year);
CREATE INDEX ix_fee_payment_date ON fee_payment (payment_date);

CREATE TABLE salary_record (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id  BIGINT         NOT NULL REFERENCES teacher (id),
    month       VARCHAR(7)     NOT NULL,
    base_amount NUMERIC(12, 2) NOT NULL,
    allowances  NUMERIC(12, 2) NOT NULL DEFAULT 0,
    deductions  NUMERIC(12, 2) NOT NULL DEFAULT 0,
    net_amount  NUMERIC(12, 2) NOT NULL,
    status      VARCHAR(10)    NOT NULL DEFAULT 'PENDING',
    paid_date   DATE,
    mode        VARCHAR(15),
    remarks     VARCHAR(300),
    created_at  TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ    NOT NULL DEFAULT now(),
    UNIQUE (teacher_id, month)
);

CREATE TABLE expense (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category     VARCHAR(60)    NOT NULL,
    description  VARCHAR(300)   NOT NULL,
    amount       NUMERIC(12, 2) NOT NULL,
    expense_date DATE           NOT NULL,
    paid_to      VARCHAR(150),
    mode         VARCHAR(15),
    created_by   VARCHAR(190),
    created_at   TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ    NOT NULL DEFAULT now()
);
CREATE INDEX ix_expense_date ON expense (expense_date);

CREATE TABLE facility (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title          VARCHAR(150) NOT NULL,
    title_hi       VARCHAR(150),
    description    TEXT,
    description_hi TEXT,
    image_url      VARCHAR(300),
    icon           VARCHAR(40),
    display_order  INT          NOT NULL DEFAULT 0,
    published      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE gallery_album (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(150) NOT NULL,
    title_hi    VARCHAR(150),
    category    VARCHAR(30)  NOT NULL,
    event_date  DATE,
    published   BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE gallery_photo (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    album_id      BIGINT       NOT NULL REFERENCES gallery_album (id) ON DELETE CASCADE,
    url           VARCHAR(300) NOT NULL,
    caption       VARCHAR(250),
    display_order INT          NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_gallery_photo_album ON gallery_photo (album_id);

CREATE TABLE announcement (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title        VARCHAR(200) NOT NULL,
    title_hi     VARCHAR(200),
    body         TEXT,
    body_hi      TEXT,
    publish_date DATE         NOT NULL,
    pinned       BOOLEAN      NOT NULL DEFAULT FALSE,
    published    BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE site_setting (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    setting_key VARCHAR(100) NOT NULL UNIQUE,
    group_name VARCHAR(60)  NOT NULL,
    label      VARCHAR(150) NOT NULL,
    kind       VARCHAR(10)  NOT NULL DEFAULT 'TEXT',
    value_en   TEXT,
    value_hi   TEXT,
    sort_order INT          NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE management_member (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(150) NOT NULL,
    designation   VARCHAR(150) NOT NULL,
    designation_hi VARCHAR(150),
    photo_url     VARCHAR(300),
    display_order INT          NOT NULL DEFAULT 0,
    published     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE testimonial (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(150) NOT NULL,
    role          VARCHAR(200),
    quote         TEXT         NOT NULL,
    quote_hi      TEXT,
    photo_url     VARCHAR(300),
    display_order INT          NOT NULL DEFAULT 0,
    published     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE enquiry (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(150) NOT NULL,
    phone            VARCHAR(30)  NOT NULL,
    email            VARCHAR(190),
    class_interested VARCHAR(60),
    message          VARCHAR(2000),
    status           VARCHAR(15)  NOT NULL DEFAULT 'NEW',
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_email  VARCHAR(190),
    action      VARCHAR(20)  NOT NULL,
    entity_type VARCHAR(60),
    entity_id   VARCHAR(60),
    summary     VARCHAR(500),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_audit_created ON audit_log (created_at DESC);
